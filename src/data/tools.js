export function getToolsByCategory(slug) {
  return tools.filter((t) => t.category === slug);
}

export function getCategory(slug) {
  return categories.find((c) => c.slug === slug);
}

// 双语取值：英文缺失时回退中文（第一阶段工具正文以中文为主，英文后续补齐）。
export function toolI18n(tool, lang) {
  const pick = (f) => (lang !== 'zh' && tool[`${f}_${lang}`] ? tool[`${f}_${lang}`] : tool[f]);
  return {
    name: pick('name'),
    desc: pick('desc'),
    keywords: lang !== 'zh' && tool.keywords_en ? tool.keywords_en : tool.keywords || [],
  };
}

export function categoryI18n(c, lang) {
  return { name: lang !== 'zh' && c.name_en ? c.name_en : c.name };
}
